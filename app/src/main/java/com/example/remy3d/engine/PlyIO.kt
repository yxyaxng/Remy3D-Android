package com.example.remy3d.engine

import java.io.BufferedWriter
import java.io.File
import java.io.FileWriter

/**
 * PlyExporter – 导出标准 PLY 格式点云文件
 *
 * 生成的 .ply 可以用 MeshLab / CloudCompare / Blender 等打开
 */
object PlyExporter {

    /**
     * 导出为 ASCII PLY（通用兼容）
     */
    fun exportAscii(points: List<SplatPoint>, file: File) {
        BufferedWriter(FileWriter(file)).use { w ->
            // PLY 头
            w.write("ply\n")
            w.write("format ascii 1.0\n")
            w.write("comment Generated by Remy3D Android Demo\n")
            w.write("comment Point count: ${points.size}\n")
            w.write("element vertex ${points.size}\n")
            w.write("property float x\n")
            w.write("property float y\n")
            w.write("property float z\n")
            w.write("property uchar red\n")
            w.write("property uchar green\n")
            w.write("property uchar blue\n")
            w.write("property uchar alpha\n")
            w.write("property float size\n")
            w.write("end_header\n")

            // 顶点数据
            for (p in points) {
                val r = (p.r * 255).toInt().coerceIn(0, 255)
                val g = (p.g * 255).toInt().coerceIn(0, 255)
                val b = (p.b * 255).toInt().coerceIn(0, 255)
                val a = (p.alpha * 255).toInt().coerceIn(0, 255)
                w.write("%.6f %.6f %.6f %d %d %d %d %.6f\n".format(
                    p.x, p.y, p.z, r, g, b, a, p.size
                ))
            }
        }
    }
}

/**
 * PlyLoader – 加载 PLY 点云文件
 */
object PlyLoader {

    fun load(file: File): List<SplatPoint> {
        val lines = file.readLines()
        val points = mutableListOf<SplatPoint>()

        var headerEnd = -1
        var vertexCount = 0
        val propertyNames = mutableListOf<String>()

        // 解析头部
        for ((i, line) in lines.withIndex()) {
            when {
                line.startsWith("element vertex") -> {
                    vertexCount = line.split(" ").last().toIntOrNull() ?: 0
                }
                line.startsWith("property") -> {
                    propertyNames.add(line.split(" ").last())
                }
                line == "end_header" -> {
                    headerEnd = i
                    break
                }
            }
        }

        if (headerEnd < 0) return emptyList()

        // 属性索引映射
        val xIdx = propertyNames.indexOf("x")
        val yIdx = propertyNames.indexOf("y")
        val zIdx = propertyNames.indexOf("z")
        val rIdx = propertyNames.indexOf("red")
        val gIdx = propertyNames.indexOf("green")
        val bIdx = propertyNames.indexOf("blue")
        val aIdx = propertyNames.indexOf("alpha")
        val sIdx = propertyNames.indexOf("size")

        // 解析顶点数据
        val dataStart = headerEnd + 1
        val dataEnd = minOf(dataStart + vertexCount, lines.size)
        for (i in dataStart until dataEnd) {
            val parts = lines[i].trim().split("\\s+".toRegex())
            if (parts.size < 3) continue

            try {
                val x = parts.getOrNull(xIdx)?.toFloat() ?: continue
                val y = parts.getOrNull(yIdx)?.toFloat() ?: continue
                val z = parts.getOrNull(zIdx)?.toFloat() ?: continue
                val r = (parts.getOrNull(rIdx)?.toFloat() ?: 200f) / 255f
                val g = (parts.getOrNull(gIdx)?.toFloat() ?: 200f) / 255f
                val b = (parts.getOrNull(bIdx)?.toFloat() ?: 200f) / 255f
                val a = (parts.getOrNull(aIdx)?.toFloat() ?: 220f) / 255f
                val s = parts.getOrNull(sIdx)?.toFloat() ?: 0.02f

                points.add(SplatPoint(x, y, z, r, g, b, s, a))
            } catch (_: Exception) { continue }
        }

        return points
    }
}
